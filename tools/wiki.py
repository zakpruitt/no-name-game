"""Rebuild the wiki's data in docs/wiki/.

    python tools/wiki.py           export the game's tables (data.js) and check notes.js covers every id

data.js is generated by tools/wiki_data.gd (headless Godot, a few seconds) from kit_slots.gd, move_list.gd,
hero_moves.gd, void_element.gd (BREAKERS, RULES), comic_fx.gd (the words), kit.gd, counter.gd and
training_dummy.gd. notes.js is hand-written: each move's state and best situation, each breaker ending's best
situation. tests/wiki_check.gd (in `agent.sh check`) fails when data.js is stale.

Screenshots in docs/wiki/img/ are taken by hand, windowed, with the game's own tools, then cropped to jpg:
    godot --path . -s tests/string_film.gd -- --dir=wiki_film --no-awaken    every bot string, 12 fps
    godot --path . -s tests/heretic_shots.gd                                the hero
    godot --path . -s tests/element_shots.gd -- --only=<id>                 one move or breaker
Open docs/wiki/index.html in a browser to read the result.
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIKI = os.path.join(ROOT, "docs", "wiki")
NOISE = ("RID", "PagedAllocator", "Leaked instance", "instance_notify", "utilities.cpp", "resources still in use", "ObjectDB instances", "at: cleanup", "at: clear",
         "Godot Engine v")


def load_js(name, var):
    s = open(os.path.join(WIKI, name), encoding="utf-8").read()
    s = s[s.rindex("window.%s =" % var) + len("window.%s =" % var):].strip().rstrip(";")
    return json.loads(s)


def check_notes():
    data, notes = load_js("data.js", "WIKI"), load_js("notes.js", "NOTES")
    card = data["cards"]["heretic"]
    ids = [i for fill in card["fill"].values() for i in fill if i != "CB"] + list(card["route"])
    ids += [i for u in card["upgrades"].values() for i in u["moves"]]
    endings = []
    for b in data["breakers"].values():
        endings.append(b["name"])
        if "alt" in b:
            endings.append(b["alt"]["name"])
    missing = ["moves." + i for i in ids if i not in notes["moves"]]
    missing += ["endings." + e for e in endings if e not in notes["endings"]]
    stale = [i for i in notes["moves"] if i not in ids] + [e for e in notes["endings"] if e not in endings]
    if missing:
        print("[wiki] needs notes (docs/wiki/notes.js):", ", ".join(missing))
    if stale:
        print("[wiki] notes for ids no longer in the game:", ", ".join(stale))
    if not missing and not stale:
        print("[wiki] notes cover every move and ending")
    return not missing


def main():
    cmd = ["godot", "--headless", "--path", ROOT, "-s", "tools/wiki_data.gd"]
    out = subprocess.run(cmd, capture_output=True, text=True, timeout=240, encoding="utf-8", errors="replace")
    for line in (out.stdout + out.stderr).splitlines():
        if line.strip() and not any(n in line for n in NOISE):
            print(line)
    ok = check_notes()
    print("[wiki] open", os.path.join(WIKI, "index.html"))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
